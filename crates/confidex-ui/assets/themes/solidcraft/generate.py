"""Map the vendored SolidCraft palettes to Confidex roles. No network or packages."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parents[2] / "src/theme/solidcraft.rs"
ROLES = {
    "background": "field",
    "surface": "panel",
    "control": "control_fill",
    "hover": "hover",
    "pressed": "selected_bg",
    "border": "control_border",
    "text": "text",
    "text_muted": "text_dim",
    "accent": "accent",
    "on_accent": "on_accent",
    "error": "error",
    "success": "form_success",
    "warning": "warning",
}


def luminance(rgb):
    channels = [v / 255 for v in rgb]
    channels = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
                for v in channels]
    return sum(a * b for a, b in zip(channels, (0.2126, 0.7152, 0.0722)))


def contrast(a, b):
    a, b = sorted((luminance(a), luminance(b)))
    return (b + 0.05) / (a + 0.05)


def readable(color, backgrounds):
    """Keep authored colour when readable; otherwise choose its nearest safe shade."""
    candidates = []
    for target in [(0, 0, 0), (255, 255, 255)]:
        for step in range(256):
            candidate = tuple(round(a + (b - a) * step / 255)
                              for a, b in zip(color, target))
            if all(contrast(candidate, bg) >= 4.5 for bg in backgrounds):
                candidates.append((step, candidate))
                break
    assert candidates, (color, backgrounds)
    return min(candidates)[1]


def generate():
    sources = [(p, json.loads(p.read_text())) for p in ROOT.glob("*.json")]
    sources.sort(key=lambda item: (item[1]["order"], item[0].stem))
    lines = ["// Generated by assets/themes/solidcraft/generate.py; see its README.md.",
             "use super::{BASE_THEMES, Palette, Theme};", "use eframe::egui::Color32;", "",
             f"pub const THEMES: [Theme; {len(sources) + 2}] = [",
             "    BASE_THEMES[0],", "    BASE_THEMES[1],"]
    for path, data in sources:
        colors = data["colors"]
        palette = {}
        for role, key in ROLES.items():
            value = colors.get(key, colors.get("agent_ok") if role == "success" else None)
            assert value and len(value) == 7, (path, role, value)
            palette[role] = tuple(bytes.fromhex(value[1:]))
        original = palette.copy()
        # CAD hover/selection fills need not carry body text; our buttons do.
        for role in ["hover", "pressed"]:
            if contrast(palette["text"], palette[role]) < 4.5:
                palette[role] = palette["control"]
        backgrounds = [palette[r] for r in ["background", "surface", "control", "hover", "pressed"]]
        palette["text"] = readable(palette["text"], backgrounds)
        backgrounds = [palette[r] for r in ["background", "surface", "control"]]
        for role in ["text_muted", "accent", "error", "success", "warning"]:
            palette[role] = readable(palette[role], backgrounds)
        palette["on_accent"] = readable(palette["on_accent"], [palette["accent"]])
        lines += ["    Theme {", f'        id: "{path.stem}",',
                  f'        label: "theme-{path.stem}",',
                  f'        dark: {str(data["base"] == "dark").lower()},',
                  "        colors: Palette {"]
        for role, rgb in palette.items():
            if rgb != original[role]:
                authored = "#" + bytes(original[role]).hex()
                lines.append(f"            // Adapted from {authored} for text contrast.")
            lines.append(f'            {role}: Color32::from_rgb({", ".join(map(str, rgb))}),')
        lines += ["        },", "    },"]
    lines += ["];", ""]
    OUTPUT.write_text("\n".join(lines))


if __name__ == "__main__":
    generate()
